let specCount = 0;
let benchCount = 0;

for (const [slug, entry] of Object.entries(DEVICES)) {
  const device = await prisma.device.findUnique({ where: { slug } });
  if (!device) {
    console.log(`  skip "${slug}" — device not found`);
    continue;
  }

  await prisma.deviceSpec.upsert({
    where: { deviceId: device.id },
    update: { ...entry.spec, sourceName: "GSMArena", sourceUrl: entry.sourceUrl },
    create: { deviceId: device.id, ...entry.spec, sourceName: "GSMArena", sourceUrl: entry.sourceUrl },
  });
  specCount++;

  if (entry.benchmark) {
    await prisma.deviceBenchmark.upsert({
      where: {
        deviceId_family_metric_sourceUrl: {
          deviceId: device.id,
          family: entry.benchmark.family,
          metric: entry.benchmark.metric,
          sourceUrl: entry.sourceUrl,
        },
      },
      update: { value: entry.benchmark.value, sourceName: "GSMArena" },
      create: {
        deviceId: device.id,
        family: entry.benchmark.family,
        metric: entry.benchmark.metric,
        value: entry.benchmark.value,
        sourceName: "GSMArena",
        sourceUrl: entry.sourceUrl,
      },
    });
    benchCount++;
  }

  console.log(`  done: ${slug}${entry.benchmark ? ` (${entry.benchmark.family} ${entry.benchmark.value})` : " (no benchmark published)"}`);
}

console.log(`\n${specCount} spec sheets, ${benchCount} benchmarks upserted.`);
